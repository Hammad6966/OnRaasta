const express = require('express');
const auth = require('../controllers/auth.controller');
const validate = require('../middleware/request-validation');
const { authLimiter } = require('../middleware/rate-limit.middleware');
const router = express.Router();
router.use((req, res, next) => { res.set('Cache-Control', 'no-store'); next(); });
router.get('/session', require('../middleware/auth.middleware').verifyToken, auth.session);
router.use(authLimiter);
router.post('/register', validate.register, auth.register);
router.post('/verify-otp', validate.otp, auth.verifyOtp);
router.post('/login', validate.login, auth.login);
router.post('/refresh', validate.refresh, auth.refresh);
router.post('/logout', validate.refresh, auth.logout);
router.post('/resend-otp', validate.resend, auth.resendOtp);
module.exports = router;
