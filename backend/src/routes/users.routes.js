const router = require('express').Router();
const { verifyToken, verifyRole } = require('../middleware/auth.middleware');
const v = require('../middleware/request-validation');
const c = require('../controllers/users.controller');
router.use(verifyToken);
router.get('/profile', c.getProfile);
router.patch('/profile', v.profile, c.updateProfile);
router.get('/vehicles', verifyRole('user'), c.listVehicles);
router.post('/vehicles', verifyRole('user'), v.vehicleCreate, c.saveVehicle);
router.patch('/vehicles/:id', verifyRole('user'), v.id, v.vehicleUpdate, c.saveVehicle);
router.delete('/vehicles/:id', verifyRole('user'), v.id, c.deleteVehicle);
module.exports = router;
